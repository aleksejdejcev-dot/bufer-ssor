"""
Контакты экстренных служб и горячих линий психологической помощи.

ВНИМАНИЕ:
Перед запуском проверить актуальность номеров на сайтах организаций; при необходимости добавить региональные.
"""

from typing import List, Dict

# Реестр проверенных горячих линий экстренной и кризисной помощи
HOTLINES: List[Dict[str, str]] = [
    {
        "name": "Единая служба экстренной помощи",
        "phone": "112",
        "description": "Общероссийская служба при непосредственной угрозе жизни или насилию",
    },
    {
        "name": "Всероссийский телефон доверия для женщин, пострадавших от насилия",
        "phone": "8-800-7000-600",
        "description": "Бесплатно, анонимно, помощь в кризисных ситуациях",
    },
]


def get_hotlines_text() -> str:
    """Форматирует контакты экстренных линий для включения в safety_note."""
    lines = [
        "Контакты экстренных служб и помощи:",
    ]
    for h in HOTLINES:
        lines.append(f"• {h['name']}: {h['phone']} — {h['description']}")
    return "\n".join(lines)

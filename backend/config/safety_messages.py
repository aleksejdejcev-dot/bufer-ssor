"""
Фиксированные сообщения безопасности сервиса «Буфер Ссор» (Этап 3.2):
1. high: Одинаковый нейтральный текст для обоих партнёров на «ты», без деления на роли и ярлыков.
2. elevated: Фиксированный нейтральный шаблон safety_note, не упоминающий тему ссоры.
"""

from config.hotlines import get_hotlines_text

HIGH_RISK_BASE_MESSAGE = (
    "Из рассказов обоих мне стало понятно, что сейчас важнее всего безопасность, а не примирение. "
    "Поэтому я не буду готовить разбор и скрипты. Если есть угроза жизни или рядом происходит насилие, "
    "звони 112. Если страшно или небезопасно, можно поговорить со специалистом или службой помощи прямо "
    "сейчас и анонимно. Ты не обязан(а) решать всё в одиночку."
)

ELEVATED_RISK_SAFETY_NOTE = (
    "Если в общении нарастает давление или страх, подумайте о поддержке специалиста или доверенного человека. "
    "При угрозе жизни звоните 112."
)


def get_high_risk_message() -> str:
    """Возвращает полный текст безопасности при высоком риске с экстренными номерами."""
    hotlines_block = get_hotlines_text()
    return f"{HIGH_RISK_BASE_MESSAGE}\n\n{hotlines_block}"


def get_elevated_risk_message() -> str:
    """Возвращает фиксированный шаблон безопасности при повышенном риске (elevated)."""
    return ELEVATED_RISK_SAFETY_NOTE

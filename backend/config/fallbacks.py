def get_random_fallback(field_path: str) -> Any:
    """Возвращает случайный статический безопасный вариант для указанного поля."""
    clean_path = field_path.lower()
    if "validation" in clean_path:
        return random.choice(FALLBACK_VALIDATION_OPTIONS)
    if "partner_perspective" in clean_path:
        return random.choice(FALLBACK_PARTNER_PERSPECTIVE_OPTIONS)
    if "blind_spot" in clean_path:
        return random.choice(FALLBACK_BLIND_SPOT_OPTIONS)
    if "action_scripts" in clean_path:
        return random.choice(FALLBACK_ACTION_SCRIPTS_OPTIONS)
    if "situation_overview" in clean_path:
        return random.choice(FALLBACK_SITUATION_OVERVIEW_OPTIONS)
    if "shared_advice" in clean_path:
        return random.choice(FALLBACK_SHARED_ADVICE_OPTIONS)
    if "conversation_starter" in clean_path:
        return random.choice(FALLBACK_CONVERSATION_STARTER_OPTIONS)
    if "shared_summary" in clean_path:
        return {
            "situation_overview": random.choice(FALLBACK_SITUATION_OVERVIEW_OPTIONS),
            "shared_advice": random.choice(FALLBACK_SHARED_ADVICE_OPTIONS),
            "conversation_starter": random.choice(FALLBACK_CONVERSATION_STARTER_OPTIONS),
        }
    return random.choice(FALLBACK_PARTNER_PERSPECTIVE_OPTIONS)


